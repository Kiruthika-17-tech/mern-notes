var grade="C"
switch(grade){
    case 'A':
        console.log("excellent")
        break
    case 'B':
        console.log("very good")
        break
    case 'C':
        console.log("Good")
        break
    case 'D':
        console.log("Fail")
        break
    default:
        console.log("invalid grade")
}